
import { useState, useEffect } from 'react';
import { Dialog, DialogContent, DialogHeader, DialogTitle } from '@/components/ui/dialog';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Separator } from '@/components/ui/separator';
import { CreditCard, Banknote, QrCode, Smartphone } from 'lucide-react';
import { CartItem, PaymentMethod } from '@/types';
import { supabase } from '@/integrations/supabase/client';
import { toast } from '@/hooks/use-toast';

interface OptimizedPaymentModalProps {
  isOpen: boolean;
  onClose: () => void;
  total: number;
  onPayment: (paymentMethod: PaymentMethod, cashReceived?: number) => void;
  cartItems: CartItem[];
  billDiscount: number;
  billDiscountType: 'percent' | 'amount';
  selectedMember?: {
    id: string;
    phone: string;
    name: string;
    email?: string;
    tier: 'silver' | 'gold' | 'platinum';
    points: number;
    total_spent: number;
  } | null;
}

const OptimizedPaymentModal = ({
  isOpen,
  onClose,
  total,
  onPayment,
  cartItems,
  billDiscount,
  billDiscountType,
  selectedMember
}: OptimizedPaymentModalProps) => {
  const [selectedMethod, setSelectedMethod] = useState<PaymentMethod>('cash');
  const [cashReceived, setCashReceived] = useState(total);
  const [isProcessing, setIsProcessing] = useState(false);

  const change = cashReceived - total;

  useEffect(() => {
    if (isOpen) {
      setCashReceived(total);
      setSelectedMethod('cash');
      setIsProcessing(false);
    }
  }, [isOpen, total]);

  const paymentMethods = [
    { id: 'cash' as PaymentMethod, label: 'เงินสด', icon: Banknote, color: 'bg-green-500' },
    { id: 'card' as PaymentMethod, label: 'บัตรเครดิต', icon: CreditCard, color: 'bg-blue-500' },
    { id: 'qr' as PaymentMethod, label: 'QR Code', icon: QrCode, color: 'bg-purple-500' },
    { id: 'transfer' as PaymentMethod, label: 'โอนเงิน', icon: Smartphone, color: 'bg-orange-500' }
  ];

  const handlePayment = async () => {
    if (selectedMethod === 'cash' && cashReceived < total) {
      toast({
        title: "เงินไม่พอ",
        description: "กรุณาใส่จำนวนเงินที่รับมากกว่าหรือเท่ากับยอดชำระ",
        variant: "destructive"
      });
      return;
    }

    setIsProcessing(true);

    try {
      // Create order data immediately without waiting
      const orderData = {
        order_number: '', // Will be generated by database function
        total_amount: total,
        payment_method: selectedMethod,
        cash_received: selectedMethod === 'cash' ? cashReceived : total,
        change_amount: selectedMethod === 'cash' ? change : 0,
        customer_id: selectedMember?.id || null,
        discount_amount: billDiscount,
        discount_type: billDiscountType,
        status: 'completed' as const,
        items: cartItems.map(item => ({
          menu_item_id: item.menu_item.id,
          quantity: item.quantity,
          unit_price: item.menu_item.price,
          total_price: item.total_price,
          addons: item.selected_addons.map(addon => ({
            addon_id: addon.id,
            name: addon.name,
            price: addon.price
          })),
          item_discount: item.item_discount,
          item_discount_type: item.item_discount_type
        }))
      };

      // Start order creation in background without blocking UI
      const orderPromise = supabase
        .from('orders')
        .insert(orderData)
        .select('*')
        .single();

      // Update member points if applicable (non-blocking)
      if (selectedMember) {
        const pointsToAdd = Math.floor(total / 10);
        supabase
          .from('members')
          .update({ 
            points: selectedMember.points + pointsToAdd,
            total_spent: selectedMember.total_spent + total
          })
          .eq('id', selectedMember.id)
          .then(() => {
            console.log(`Added ${pointsToAdd} points to member ${selectedMember.name}`);
          })
          .catch(console.error);
      }

      // Process payment immediately
      onPayment(selectedMethod, selectedMethod === 'cash' ? cashReceived : undefined);
      
      // Show success message immediately
      toast({
        title: "ชำระเงินสำเร็จ",
        description: `ชำระด้วย${paymentMethods.find(m => m.id === selectedMethod)?.label} จำนวน ฿${total}`,
      });

      // Wait for order creation in background
      orderPromise
        .then(({ data, error }) => {
          if (error) {
            console.error('Order creation error:', error);
            toast({
              title: "เกิดข้อผิดพลาด",
              description: "ไม่สามารถบันทึกออเดอร์ได้ กรุณาตรวจสอบระบบ",
              variant: "destructive"
            });
          } else {
            console.log('Order created successfully:', data?.order_number);
          }
        })
        .catch(console.error);

    } catch (error) {
      console.error('Payment processing error:', error);
      toast({
        title: "เกิดข้อผิดพลาด",
        description: "ไม่สามารถประมวลผลการชำระเงินได้",
        variant: "destructive"
      });
    } finally {
      setIsProcessing(false);
    }
  };

  const quickCashButtons = [
    { amount: 100, label: '100' },
    { amount: 500, label: '500' },
    { amount: 1000, label: '1000' },
    { amount: Math.ceil(total / 100) * 100, label: 'พอดี' }
  ];

  return (
    <Dialog open={isOpen} onOpenChange={onClose}>
      <DialogContent className="max-w-md">
        <DialogHeader>
          <DialogTitle className="text-coffee-800">ชำระเงิน</DialogTitle>
        </DialogHeader>

        <div className="space-y-4">
          {/* Total Amount */}
          <div className="text-center py-4 bg-coffee-50 rounded-lg">
            <div className="text-2xl font-bold text-coffee-800">฿{total.toFixed(2)}</div>
            <div className="text-sm text-coffee-600">ยอดชำระสุทธิ</div>
          </div>

          {/* Payment Methods */}
          <div className="grid grid-cols-2 gap-2">
            {paymentMethods.map((method) => {
              const Icon = method.icon;
              return (
                <Button
                  key={method.id}
                  variant={selectedMethod === method.id ? "default" : "outline"}
                  onClick={() => setSelectedMethod(method.id)}
                  className={`h-16 flex flex-col gap-1 ${
                    selectedMethod === method.id 
                      ? `${method.color} text-white` 
                      : 'border-coffee-200 text-coffee-700'
                  }`}
                >
                  <Icon className="w-5 h-5" />
                  <span className="text-xs">{method.label}</span>
                </Button>
              );
            })}
          </div>

          {/* Cash Input */}
          {selectedMethod === 'cash' && (
            <>
              <Separator />
              <div className="space-y-3">
                <div>
                  <Label htmlFor="cash-received">จำนวนเงินที่รับ</Label>
                  <Input
                    id="cash-received"
                    type="number"
                    value={cashReceived}
                    onChange={(e) => setCashReceived(Number(e.target.value))}
                    className="text-lg text-center"
                    min={0}
                    step={0.01}
                  />
                </div>

                {/* Quick Cash Buttons */}
                <div className="grid grid-cols-4 gap-2">
                  {quickCashButtons.map((btn) => (
                    <Button
                      key={btn.amount}
                      variant="outline"
                      size="sm"
                      onClick={() => setCashReceived(btn.amount)}
                      className="text-xs"
                    >
                      {btn.label}
                    </Button>
                  ))}
                </div>

                {/* Change Display */}
                <div className="text-center py-2">
                  <div className={`text-lg font-medium ${
                    change >= 0 ? 'text-green-600' : 'text-red-600'
                  }`}>
                    เงินทอน: ฿{change.toFixed(2)}
                  </div>
                </div>
              </div>
            </>
          )}

          {/* Payment Button */}
          <Button
            onClick={handlePayment}
            disabled={isProcessing || (selectedMethod === 'cash' && cashReceived < total)}
            className="w-full h-12 text-lg bg-coffee-600 hover:bg-coffee-700"
          >
            {isProcessing ? 'กำลังประมวลผล...' : 'ชำระเงิน'}
          </Button>
        </div>
      </DialogContent>
    </Dialog>
  );
};

export default OptimizedPaymentModal;
